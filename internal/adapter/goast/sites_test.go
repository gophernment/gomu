package goast_test

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/token"
	"slices"
	"strings"
	"testing"

	"github.com/gophernment/gomu/internal/adapter/goast"
	"github.com/gophernment/gomu/internal/mutant"
	"github.com/gophernment/gomu/internal/mutator"
)

const sitesSrc = `package p

func f(a, b int) bool {
	if a < b && a+b > 3 {
		return true
	}
	return a*b == 0
}
`

func allMutators() []mutator.Mutator {
	return []mutator.Mutator{mutator.Arithmetic{}, mutator.Conditional{}, mutator.Logical{}}
}

func parseSrc(t *testing.T, src string) *goast.File {
	t.Helper()

	root := t.TempDir()
	writeFile(t, root, "add.go", src)

	f, err := goast.Parse(root, "add.go")
	if err != nil {
		t.Fatal(err)
	}
	return f
}

func describe(sites []goast.Site) []string {
	out := make([]string, len(sites))
	for i, s := range sites {
		m := s.Mutant
		out[i] = fmt.Sprintf("%s %v %s->%s", m.Operator, m.Pos, m.Original, m.Replacement)
	}
	return out
}

func render(t *testing.T, f *goast.File) string {
	t.Helper()

	var buf bytes.Buffer
	if err := format.Node(&buf, f.Fset, f.AST); err != nil {
		t.Fatal(err)
	}
	return buf.String()
}

func TestSitesOrderedByPosition(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, sitesSrc)

	want := []string{
		"conditional add.go:4:7 <-><=",
		"logical add.go:4:11 &&->||",
		"arithmetic add.go:4:15 +->-",
		"conditional add.go:4:18 >->>=",
		"arithmetic add.go:7:10 *->/",
		"conditional add.go:7:13 ==->!=",
	}
	if got := describe(f.Sites(allMutators())); !slices.Equal(got, want) {
		t.Errorf("Sites() =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

func TestSitesAreDeterministic(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, sitesSrc)

	first := describe(f.Sites(allMutators()))
	for range 5 {
		if got := describe(f.Sites(allMutators())); !slices.Equal(got, first) {
			t.Fatalf("Sites() order changed between calls:\n%v\n%v", first, got)
		}
	}
}

func TestSitesStartPending(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, sitesSrc)

	for _, s := range f.Sites(allMutators()) {
		if s.Mutant.Status != mutant.Pending {
			t.Errorf("%v status = %v, want %v", s.Mutant.Pos, s.Mutant.Status, mutant.Pending)
		}
	}
}

func TestSitesApplyAndRevertOnRealFile(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, sitesSrc)
	before := render(t, f)

	sites := f.Sites([]mutator.Mutator{mutator.Conditional{}})
	if len(sites) == 0 {
		t.Fatal("no sites found")
	}

	first := sites[0].Mutation
	first.Apply()
	if got := render(t, f); !strings.Contains(got, "a <= b") {
		t.Errorf("after Apply the file does not contain the mutation:\n%s", got)
	}

	first.Revert()
	if got := render(t, f); got != before {
		t.Errorf("Revert did not restore the file:\n%s\nwant\n%s", got, before)
	}
}

func TestSitesUseOperatorLine(t *testing.T) {
	t.Parallel()

	// The expression starts on line 4 but the operator is on line 5, which is
	// the line coverage data must be matched against.
	src := "package p\n\nfunc f(a, b int) int {\n\treturn a +\n\t\tb\n}\n"
	f := parseSrc(t, src)

	sites := f.Sites(allMutators())
	if len(sites) != 1 {
		t.Fatalf("got %d sites, want 1", len(sites))
	}
	if got := sites[0].Mutant.Pos.Line; got != 4 {
		t.Errorf("Line = %d, want 4 (operator line)", got)
	}
}

func TestSitesNone(t *testing.T) {
	t.Parallel()

	tests := []struct {
		name     string
		src      string
		mutators []mutator.Mutator
	}{
		{"no mutators", sitesSrc, nil},
		{"nil mutator entries are skipped", sitesSrc, []mutator.Mutator{nil}},
		{"no matching code", "package p\n\nfunc f() {}\n", allMutators()},
		{
			"generated file",
			"// Code generated by tool; DO NOT EDIT.\n\npackage p\n\nfunc f(a, b int) int { return a + b }\n",
			allMutators(),
		},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			t.Parallel()

			f := parseSrc(t, tt.src)
			if got := f.Sites(tt.mutators); len(got) != 0 {
				t.Errorf("Sites() = %v, want none", describe(got))
			}
		})
	}
}

func TestSitesSkipsNilMutatorButKeepsOthers(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, sitesSrc)

	got := f.Sites([]mutator.Mutator{nil, mutator.Logical{}})
	if want := []string{"logical add.go:4:11 &&->||"}; !slices.Equal(describe(got), want) {
		t.Errorf("Sites() = %v, want %v", describe(got), want)
	}
}

// fakeMutator reports one mutation on every identifier, to prove Sites works
// with any Mutator and keeps registration order for equal positions.
type fakeMutator struct{ name string }

func (m fakeMutator) Name() string { return m.name }

func (m fakeMutator) Mutations(n ast.Node) []mutator.Mutation {
	id, ok := n.(*ast.Ident)
	if !ok || id.Name != "x" {
		return nil
	}
	return []mutator.Mutation{{
		Pos:         token.Pos(id.Pos()),
		Original:    "x",
		Replacement: "y",
		Apply:       func() { id.Name = "y" },
		Revert:      func() { id.Name = "x" },
	}}
}

func TestSitesKeepMutatorOrderAtSamePosition(t *testing.T) {
	t.Parallel()

	f := parseSrc(t, "package p\n\nfunc g() { _ = x }\n")

	got := describe(f.Sites([]mutator.Mutator{fakeMutator{"second"}, fakeMutator{"first"}}))
	want := []string{"second add.go:3:16 x->y", "first add.go:3:16 x->y"}
	if !slices.Equal(got, want) {
		t.Errorf("Sites() = %v, want %v", got, want)
	}
}

func TestSitesOnlyInsideFunctionBodies(t *testing.T) {
	t.Parallel()

	const src = `package p

import "fmt"

var global = 1 + 2

const limit = 10 * 2

var table = [1 + 1]int{}

var handler = func(a, b int) int { return a + b }

type T struct{ n [2 * 2]int }

func sig(buf [1 + 1]byte, a, b int) int { return a * b }

func (T) method(a, b int) bool { return a < b }

func decl()

func nested(a, b int) int {
	f := func() int { return a - b }
	return f() + 1
}

func init() { fmt.Println(1 / 2) }
`
	f := parseSrc(t, src)

	want := []string{
		"arithmetic add.go:11:45 +->-",   // package-level func literal
		"arithmetic add.go:15:52 *->/",   // function body, not the [1 + 1] in its signature
		"conditional add.go:17:43 <-><=", // method body
		"arithmetic add.go:22:29 -->+",   // func literal inside a function
		"arithmetic add.go:23:13 +->-",   // statement after the literal
		"arithmetic add.go:26:29 /->*",   // init body
	}
	if got := describe(f.Sites(allMutators())); !slices.Equal(got, want) {
		t.Errorf("Sites() =\n%s\nwant\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
}

// funcMutator reports one mutation per function declaration or literal, to
// prove Sites offers whole functions to mutators, each exactly once.
type funcMutator struct{}

func (funcMutator) Name() string { return "func" }

func (funcMutator) Mutations(n ast.Node) []mutator.Mutation {
	var body *ast.BlockStmt
	switch fn := n.(type) {
	case *ast.FuncDecl:
		body = fn.Body
	case *ast.FuncLit:
		body = fn.Body
	default:
		return nil
	}
	return []mutator.Mutation{{Pos: body.Lbrace, Original: "{", Replacement: "{}", Apply: func() {}, Revert: func() {}}}
}

func TestSitesOffersEachFunctionOnce(t *testing.T) {
	t.Parallel()

	const src = `package p

var lit = func() { _ = func() {} }

type T struct{}

func (T) m() { _ = func() { _ = func() {} } }

func decl() {}

func noBody()
`
	f := parseSrc(t, src)

	got := describe(f.Sites([]mutator.Mutator{funcMutator{}}))
	// lit and its nested literal, the method and its two nested literals, decl; not the body-less noBody.
	if len(got) != 6 {
		t.Errorf("got %d sites, want 6: %v", len(got), got)
	}
}
